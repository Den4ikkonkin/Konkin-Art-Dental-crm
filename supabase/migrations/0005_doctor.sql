-- Врач в наряде.
--
-- Зачем: в наряде нужно указывать, кто из врачей ведёт работу.
-- Хранится просто строкой — список врачей задаётся в коде (model.ts, DOCTORS),
-- поэтому добавить нового врача можно без правки базы.
--
-- Запуск: Supabase → SQL Editor → вставить целиком → Run.
-- Повторный запуск безопасен.
--
-- ВАЖНО: без этой миграции приложение продолжает работать —
-- наряды читаются без врача, а при сохранении появится подсказка.
-- Но чтобы врач сохранялся, миграцию нужно выполнить.

alter table public.orders
  add column if not exists doctor text not null default '';

-- Пустая строка = врач не указан (так выглядят все наряды до миграции).
comment on column public.orders.doctor is
  'Врач, ведущий наряд. Пустая строка — не указан';

-- Индекс для сводки по врачам в отчётах.
create index if not exists orders_doctor_idx
  on public.orders (doctor);
